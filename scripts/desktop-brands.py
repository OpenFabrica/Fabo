#!/usr/bin/env python3
"""Generates desktop/brands.go from Kiri's crates/kiri/src/ui/brands.rs.

Kiri ships brand logos for commonly containerized images (Simple Icons,
CC0) and a table from image names to them. The desktop shows the same logos
on its container rows, so the two tables are carried over unchanged.

    python3 scripts/desktop-brands.py /path/to/kiri
"""
import os
import re
import subprocess
import sys


# convert reads Kiri's brands.rs and writes the same tables as Go.
def convert(kiri: str, out: str) -> None:
    source = open(os.path.join(kiri, "crates/kiri/src/ui/brands.rs"), encoding="utf-8").read()
    brands_part, images_part = source.split("pub static IMAGES")
    brands = re.findall(r'^\s+\("([^"]+)", "([0-9A-Fa-f]{6})", "([^"]+)"\),', brands_part, re.M)
    images = re.findall(r'^\s+\("([^"]+)", "([^"]+)"\),', images_part, re.M)
    if not brands or not images:
        sys.exit("brands.rs has an unexpected shape")
    lines = [
        "// Code generated by scripts/desktop-brands.py from Kiri's brands.rs; DO NOT EDIT.",
        "// Brand logos from Simple Icons (CC0); the trademarks belong to their owners.",
        "",
        "package main",
        "",
        "// brandLogos maps a Simple Icons slug to its brand color and 24-unit path.",
        "var brandLogos = map[string][2]string{",
    ]
    lines += [f'\t"{slug}": {{"{color}", "{path}"}},' for slug, color, path in brands]
    lines += [
        "}",
        "",
        "// imageBrands maps an image repository, whole or its last component, to a slug.",
        "var imageBrands = map[string]string{",
    ]
    lines += [f'\t"{name}": "{slug}",' for name, slug in images]
    lines += ["}", ""]
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    subprocess.run(["gofmt", "-w", out], check=True)
    print(f"{out}: {len(brands)} logos, {len(images)} images")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    here = os.path.dirname(os.path.abspath(__file__))
    convert(sys.argv[1], os.path.join(here, "..", "desktop", "brands.go"))
